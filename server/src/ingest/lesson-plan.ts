import type { Concept } from '@pips-notebook/shared';
import type { OutlineResult } from './outline';
import { z } from 'zod';
import { system, wrap } from '../prompts/ingest/common';

export const LessonPlanSchema = z.object({ lessons: z.array(z.object({
  title: z.string().min(5).max(120),
  description: z.string().min(30).max(1200),
  learningObjectives: z.array(z.string().min(10).max(300)).min(2).max(5),
  concepts: z.array(z.object({ sourceIds: z.array(z.string()).min(1), title: z.string().min(3).max(120), summary: z.string().min(20).max(1200) })).min(1).max(6),
})).min(1).max(6) });
export type LessonPlan = z.infer<typeof LessonPlanSchema>;
export type LessonPlanRepair = { previousPlan: LessonPlan; missingIds: string[]; duplicateIds: string[]; unknownIds: string[] };

/** Constrain the provider's structured output to this upload's actual concept ids. */
export function lessonPlanSchemaFor(concepts: Concept[]) {
  const ids = concepts.map(c => c.id);
  if (!ids.length) throw new Error('Cannot plan lessons without source concepts.');
  const concept = LessonPlanSchema.shape.lessons.element.shape.concepts.element.extend({
    sourceIds: z.array(z.enum(ids as [string, ...string[]])).min(1),
  });
  return LessonPlanSchema.extend({ lessons: z.array(LessonPlanSchema.shape.lessons.element.extend({
    concepts: z.array(concept).min(1).max(6),
  })).min(1).max(6) });
}

export class LessonPlanCoverageError extends Error {
  constructor(readonly repair: LessonPlanRepair) {
    super('Lesson plan must include every source concept exactly once, without unknown ids. ' +
      `Missing: ${repair.missingIds.join(', ') || 'none'}; repeated: ${repair.duplicateIds.join(', ') || 'none'}; unknown: ${repair.unknownIds.join(', ') || 'none'}.`);
  }
}

export const PLAN_LESSONS_SYSTEM = system(`Organize an entire uploaded lecture into coherent lessons before any questions are generated.
Usually use 3-5 rooms for a lecture, 1-2 for a short document, at most 6. These are complete teaching sessions, not individual slides or definitions. A batch/page boundary is never a lesson boundary.
Merge semantically overlapping concepts across ALL batches (for example list operations/semantics and abstract list properties). Preserve every source concept id exactly once across the plan. Merge duplicates under one concept, preserving all their source ids. Do not merge unrelated mechanisms just to reach a count.
sourceIds must contain ONLY ids from requiredSourceIds, never key-point ids, material-item ids or new ids. Check that the flattened sourceIds list is an exact permutation of requiredSourceIds before returning. If validation feedback is supplied, revise the previous plan to fix every missing, repeated or unknown id while preserving the teaching scope and evidence.
Group related prerequisites, definitions and examples together. Array review and list motivation belong together; size/capacity/backing storage together; insertion/removal together; resizing/amortized cost together when supported. These are examples of grouping, not facts to inject into another course. Brief next-topic introductions do not need their own room.
Titles should tell the learner what they will understand or do, using the actual subject and operation. Each lesson needs a 2-3 sentence plain-language description explaining its scope and 2-5 concrete teaching objectives (Explain why..., Trace how..., Compare...). Each concept needs a useful explanation of what to cover, not a restatement of its title.
Use ONLY the supplied concepts, summaries and supported key points. Add no new facts, requirements or unsupported algorithms. No answer keys, hidden misconceptions or administrative slides. Return structured JSON.`);

export const lessonPlanPrompt = (title: string, concepts: Concept[], repair?: LessonPlanRepair) =>
  wrap('material', JSON.stringify({title,requiredSourceIds:concepts.map(c=>c.id),concepts:concepts.map(c=>({id:c.id,title:c.title,summary:c.summary,
    keyPoints:c.keyPoints.map(k=>({id:k.id,statement:k.statement}))})),...(repair ? {validationFeedback:repair} : {})}));

/** Restructure by ids; evidence and question source items are carried over, never generated by the planner. */
export function applyLessonPlan(outline: OutlineResult, plan: LessonPlan): OutlineResult {
  const byId = new Map(outline.concepts.map(c => [c.id,c]));
  const assigned = plan.lessons.flatMap(l => l.concepts.flatMap(c => c.sourceIds));
  const counts = new Map<string,number>();
  for (const id of assigned) counts.set(id,(counts.get(id) ?? 0)+1);
  const missingIds = [...byId.keys()].filter(id=>!counts.has(id));
  const duplicateIds = [...counts.keys()].filter(id=>counts.get(id)!>1);
  const unknownIds = [...counts.keys()].filter(id=>!byId.has(id));
  if (missingIds.length || duplicateIds.length || unknownIds.length) {
    throw new LessonPlanCoverageError({ previousPlan: plan, missingIds, duplicateIds, unknownIds });
  }
  const remap = new Map<string,string>();
  const concepts: Concept[] = [];
  const units: OutlineResult['units'] = [];
  const rooms: OutlineResult['rooms'] = [];
  for (const [i, lesson] of plan.lessons.entries()) {
    const unitId = `u${i+1}`, ids: string[] = [];
    for (const group of lesson.concepts) {
      const sources = group.sourceIds.map(id => byId.get(id)!);
      const id = `c${concepts.length+1}`;
      ids.push(id); for (const old of group.sourceIds) remap.set(old,id);
      const seen = new Set<string>();
      const keyPoints = sources.flatMap(c => c.keyPoints).filter(k => {
        const key = k.statement.trim().toLowerCase().replace(/\s+/g,' ');
        if (seen.has(key)) return false; seen.add(key); return true;
      }).map((k,j) => ({...k,id:`${id}_k${j+1}`}));
      concepts.push({id,unitId,title:group.title,summary:group.summary,order:concepts.length+1,
        prerequisites:sources.flatMap(c => c.prerequisites),keyPoints,misconceptions:[]});
    }
    units.push({id:unitId,title:lesson.title,order:i+1,conceptIds:ids});
    rooms.push({id:`r${i+1}`,title:lesson.title,description:lesson.description,learningObjectives:lesson.learningObjectives,order:i+1,conceptIds:ids});
  }
  for (const c of concepts) c.prerequisites = [...new Set(c.prerequisites.map(id => remap.get(id)!).filter(id => id && id !== c.id))];
  return {...outline,units,rooms,concepts,materialItems:outline.materialItems.map(m => ({...m,conceptIds:[...new Set(m.conceptIds.map(id => remap.get(id)!))]}))};
}
